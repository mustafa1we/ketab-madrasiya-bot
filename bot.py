def price_context(user_text):

    products = find_all_products(user_text)

    if not products:
        return ""

    lines = []

    for product in products:

        price = PRICES[product]

        if price == 0:

            lines.append(
                f"{product}: السعر يحتاج تأكيد من المكتبة."
            )

        else:

            lines.append(
                f"{product}: {price} دينار."
            )

    return "\n".join(lines)


