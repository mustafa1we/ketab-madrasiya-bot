def deterministic_answer(chat_id, text):
    products = find_products(text)
    categories = detect_categories(text)

    # حفظ المنتجات حتى تستفيد منها الرسائل التالية
    if products:
        LAST_PRODUCTS[chat_id] = products[:10]

    # أكثر من منتج أو سؤال واضح عن منتج
    if products:
        # إذا الرسالة مجرد تحية/كلمة قصيرة لا نريد قائمة ضخمة
        answer = product_answer(products)

        # إذا كانت الرسالة تسأل أيضاً عن التوفر، نوضح أن السعر من القائمة
        if asks_availability(text) and not asks_price(text):
            answer = answer + "\nالموجود حسب قائمة الأسعار عندي 🌷"

        return answer, products

    # فئة عامة
    if categories:
        # إذا عدة فئات، نجاوب على كلها
        chunks = []

        for category in categories:
            chunk = category_answer(category)
            if chunk:
                chunks.append(chunk)

        if chunks:
            return "\n\n".join(chunks), []

    return None, []


