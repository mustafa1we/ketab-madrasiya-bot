def price_context(user_text):

    product = find_product(user_text)

    if product:

        price = PRICES[product]

        return (
            f"المنتج: {product}\n"
            f"السعر المؤكد: {price} دينار."
        )

    return ""


# =========================================================
# DeepSeek
# =========================================================

def ask_ai(user_text):

    context = price_context(user_text)

    prompt = f"""
سؤال الزبون:
{user_text}

"""

    if context:
        prompt += f"""
معلومات مؤكدة من قائمة المكتبة:
{context}

استخدم هذه المعلومات فقط ولا تغير السعر.
"""

    else:
        prompt += """
لا توجد معلومات سعر مؤكدة لهذا السؤال.
لا تخترع سعراً.
"""

    response = client.chat.completions.create(
        model=MODEL,

        messages=[
            {
                "role": "system",
                "content": SYSTEM_PROMPT
            },
            {
                "role": "user",
                "content": prompt
            }
        ],

        max_tokens=250,
        temperature=0.2
    )

    if not response.choices:
        return "السعر يحتاج تأكيد من المكتبة 🌷"

    answer = response.choices[0].message.content

    if not answer:
        return "السعر يحتاج تأكيد من المكتبة 🌷"

    # -----------------------------------------------------
    # تنظيف الكلمات الممنوعة
    # -----------------------------------------------------

    forbidden = [
        "حبيبي",
        "حبيبتي",
        "عزيزي",
        "عزيزتي",
    ]

    for word in forbidden:
        answer = answer.replace(word, "")

    answer = re.sub(r"\s{2,}", " ", answer)
    answer = answer.strip()

    return answer


# =========================================================
# إرسال Telegram
# =========================================================

def send_message(
    chat_id,
    text,
    business_connection_id=None
):

    if not text:
        text = "السعر يحتاج تأكيد من المكتبة 🌷"

    data = {
        "chat_id": chat_id,
        "text": str(text)
    }

    if business_connection_id:
        data["business_connection_id"] = business_connection_id

    response = requests.post(
        TG + "/sendMessage",
        json=data,
        timeout=30
    )

    if not response.ok:

        logging.error("TELEGRAM ERROR")
        logging.error("STATUS: %s", response.status_code)
        logging.error("RESPONSE: %s", response.text)
        logging.error("CHAT_ID: %s", chat_id)
        logging.error(
            "BUSINESS_CONNECTION: %s",
            business_connection_id
        )

    response.raise_for_status()


