def find_products_direct(text):

    normalized_text = normalize(text)

    found = []

    # المنتجات الأطول أولاً
    products = sorted(
        PRICES.keys(),
        key=lambda x: len(normalize(x)),
        reverse=True
    )

    for product in products:

        product_normalized = normalize(product)

        if product_normalized in normalized_text:

            if product not in found:
                found.append(product)

    # aliases
    for product, aliases in ALIASES.items():

        for alias in aliases:

            alias_normalized = normalize(alias)

            if alias_normalized and alias_normalized in normalized_text:

                if product not in found:
                    found.append(product)

                break

    return found


