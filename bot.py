    # نجمع الردود هنا
    # =====================================================

    replies = []


    # =====================================================
    # الطباشير
    # =====================================================

    if "طباشير" in text:

        replies.append(
            "🖍️ الطباشير: 1000 دينار."
        )


    # =====================================================
    # الطين
    # =====================================================

    if (
        "طين اسطناعي" in text
        or "طين اصطناعي" in text
    ):

        replies.append(
            "🧱 الطين الاصطناعي: 1000 دينار."
        )


    # =====================================================
    # الملازم
    # =====================================================

