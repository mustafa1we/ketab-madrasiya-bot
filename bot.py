# =========================================================
# Normalize
# =========================================================

def normalize(text):
    if not text:
        return ""

    text = str(text).lower().strip()

    replacements = {
        "أ": "ا",
        "إ": "ا",
        "آ": "ا",
        "ى": "ي",
        "ة": "ه",
    }

    for a, b in replacements.items():
        text = text.replace(a, b)

    text = re.sub(r"[\u064B-\u065F\u0670]", "", text)
    text = re.sub(r"\s+", " ", text)

    return text.strip()


# =========================================================
# البحث عن المنتجات
