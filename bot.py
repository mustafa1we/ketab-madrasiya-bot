# منع تكرار الرسائل
# =========================================================

PROCESSED_MESSAGES = set()

MAX_PROCESSED_MESSAGES = 5000


def already_processed(chat_id, message_id):

    if message_id is None:
        return False

    key = f"{chat_id}:{message_id}"

    if key in PROCESSED_MESSAGES:
        return True

    PROCESSED_MESSAGES.add(key)

    if len(PROCESSED_MESSAGES) > MAX_PROCESSED_MESSAGES:
        PROCESSED_MESSAGES.clear()

    return False


# =========================================================
# معالجة الرسالة
# =========================================================

def process_message(msg):

    if not msg:
        return

    chat = msg.get("chat")

    if not chat:
        return

    chat_id = chat.get("id")

    if not chat_id:
        return

    message_id = msg.get("message_id")

    # منع نفس الرسالة من الرد مرتين
    if already_processed(chat_id, message_id):

        logging.info(
            "Duplicate message ignored | chat_id=%s | message_id=%s",
            chat_id,
            message_id
        )

        return

    business_connection_id = msg.get(
        "business_connection_id"
    )

    logging.info(
        "Message received | chat_id=%s | business=%s | message_id=%s",
        chat_id,
        bool(business_connection_id),
        message_id
    )


    # =====================================================
    # نص
    # =====================================================

    if "text" in msg:

        text = msg.get("text", "").strip()

        if not text:
            return


        # -------------------------------------------------
        # Start
        # -------------------------------------------------

        if text.startswith("/start"):

            send_message(
                chat_id,
                "أهلاً وسهلاً 🌷\n"
                "آني المساعد الذكي لمكتبة أم القرى.\n"
                "اكتبلي شنو تحتاج.",
                business_connection_id
            )

            return


        # -------------------------------------------------
        # Help
        # -------------------------------------------------

        if text.startswith("/help"):

            send_message(
                chat_id,
                "اكتب سؤالك مباشرة 🌷\n"
                "وأجاوبك عن منتجات مكتبة أم القرى.",
                business_connection_id
            )

            return


        # -------------------------------------------------
        # الرد المباشر
        # -------------------------------------------------

        direct = direct_reply(text)

        if direct is not None:

            send_message(
                chat_id,
                direct,
                business_connection_id
            )

            return


        # -------------------------------------------------
        # إذا اسم المنتج واضح، نعطي السعر مباشرة
        # -------------------------------------------------

        product = find_product(text)

        if product:

            price = PRICES[product]

            send_message(
                chat_id,
                f"{product} سعره {price} دينار 🌷",
                business_connection_id
            )

            return


        # -------------------------------------------------
        # DeepSeek للأسئلة الباقية فقط
        # -------------------------------------------------

        try:

            answer = ask_ai(text)

            send_message(
                chat_id,
                answer,
                business_connection_id
            )

        except Exception as error:

            logging.exception("AI ERROR")

            error_text = str(error).lower()

            if (
                "429" in error_text
                or "rate limit" in error_text
                or "quota" in error_text
            ):

                error_message = (
                    "الخدمة مشغولة حالياً 🌷 "
                    "حاول بعد شوي."
                )

            elif (
                "401" in error_text
                or "api key" in error_text
                or "authentication" in error_text
            ):

                error_message = (
                    "صار خلل بإعدادات الخدمة 🌷"
                )

            else:

                error_message = (
                    "صار تأخير بسيط بالخدمة 🌷 "
                    "حاول بعد شوي."
                )

            try:

                send_message(
                    chat_id,
                    error_message,
                    business_connection_id
                )

            except Exception:

                logging.exception(
                    "Failed to send error message"
                )

        return


    # =====================================================
    # صورة / ملف
    # =====================================================

    if (
        "photo" in msg
        or "document" in msg
    ):

        send_message(
            chat_id,
            "وصلتني الصورة/الملف 🌷\n"
            "اكتبلي شنو تريد تعرف عنه.",
            business_connection_id
        )

        return


    # =====================================================
    # أي نوع ثاني
    # =====================================================

    send_message(
        chat_id,
        "أكدر أساعدك بمنتجات مكتبة أم القرى 🌷",
        business_connection_id
    )


