# =========================================================

def clean_answer(answer):

    if not answer:
        return "ممكن أعرف شنو المنتج اللي تريد تسأل عنه؟ 🌷"

    forbidden = [
        "حبيبي",
        "حبيبتي",
        "عزيزي",
        "عزيزتي"
    ]

    for word in forbidden:
        answer = answer.replace(word, "")

    # منع كشف أنه DeepSeek
    answer = re.sub(
        r"(?i)deepseek",
        "",
        answer
    )

    # منع ذكر API
    answer = re.sub(
        r"(?i)\bapi\b",
        "",
        answer
    )

    # تنظيف الفراغات
    answer = re.sub(
        r"[ \t]{2,}",
        " ",
        answer
    )

    answer = re.sub(
        r"\n{3,}",
        "\n\n",
        answer
    )

    return answer.strip()


