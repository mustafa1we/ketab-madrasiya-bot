def build_history(chat_id):

    history = CHAT_HISTORY.get(chat_id)

    if not history:
        return ""

    lines = []

    for item in history:

        role = item.get("role")
        content = item.get("content")

        if role == "user":

            lines.append(
                f"الزبون: {content}"
            )

        elif role == "assistant":

            lines.append(
                f"البوت: {content}"
            )

    return "\n".join(lines)


