def process_message(msg):
    if not msg:
        return

    chat = msg.get("chat")

    if not chat:
        return

    chat_id = chat.get("id")

    if not chat_id:
        return

    business_connection_id = msg.get("business_connection_id")

    text = (msg.get("text") or "").strip()

    logging.info(
        "MESSAGE | chat=%s | business=%s | text=%s",
        chat_id,
        bool(business_connection_id),
        text,
    )

    if not text:
        if "photo" in msg or "document" in msg:
            send_message(
                chat_id,
                "وصلتني الصورة/الملف 🌷 إذا تريد أعرفلك شي عنه، اكتبلي شنو تريد.",
                business_connection_id,
            )
        return

    # أوامر
    if text.startswith("/start"):
        intro = (
            "هلا بيك 🌷\n"
            "آني بوت مكتبة أم القرى، مو صاحب المكتبة.\n"
            "أكدر أساعدك بالمنتجات والأسعار الموجودة عندي.\n"
            "گلي شتحتاج."
        )

        send_message(
            chat_id,
            intro,
            business_connection_id,
        )

        INTRO_SENT.add(chat_id)
        HISTORY[chat_id].append(("user", text))
        HISTORY[chat_id].append(("assistant", intro))
        return

    if text.startswith("/help"):
        answer = (
            "گلي اسم الشي اللي تريده، حتى لو مكتوبه باللهجة أو بيها خطأ إملائي 🌷\n"
            "وإذا عندك أكثر من طلب بنفس الرسالة، اكتبهم كلهم وآني أجاوب عليهم."
        )

        send_message(
            chat_id,
            answer,
            business_connection_id,
        )
        return

    # سجل رسالة المستخدم
    HISTORY[chat_id].append(("user", text))

    # التعريف بالبوت يكون مرة واحدة فقط، ومندمج بالرد الأول
    first_contact = chat_id not in INTRO_SENT

    direct = direct_reply(text, chat_id)

    if direct is not None:
        answer = direct

        if first_contact and normalize(text) not in GREETINGS:
            answer = (
                "آني بوت مكتبة أم القرى، مو صاحب المكتبة 🌷\n"
                + answer
            )

        INTRO_SENT.add(chat_id)

        send_message(
            chat_id,
            answer,
            business_connection_id,
        )

        HISTORY[chat_id].append(("assistant", answer))
        return

    # أولاً: البحث البرمجي في المنتجات والأسعار
    deterministic, matched = deterministic_answer(chat_id, text)

    if deterministic:
        answer = deterministic

        if first_contact:
            answer = (
                "آني بوت مكتبة أم القرى، مو صاحب المكتبة 🌷\n"
                + answer
            )

        INTRO_SENT.add(chat_id)

        send_message(
            chat_id,
            answer,
            business_connection_id,
        )

        HISTORY[chat_id].append(("assistant", answer))
        return

    # ثانياً: ردود محادثية معروفة
    conversational = conversational_answer(chat_id, text)

    if conversational:
        answer = conversational

        if first_contact:
            answer = (
                "آني بوت مكتبة أم القرى، مو صاحب المكتبة 🌷\n"
                + answer
            )

        INTRO_SENT.add(chat_id)

        send_message(
            chat_id,
            answer,
            business_connection_id,
        )

        HISTORY[chat_id].append(("assistant", answer))
        return

    # ثالثاً: AI فقط إذا ما قدر النظام يطابق المنتج مباشرة
    try:
        answer = ask_ai(
            chat_id,
            text,
            matched_products=matched,
        )

        if not answer:
            answer = (
                "گلي اسم المنتج أو شنو تريد تعرف عنه، وآني أساعدك 🌷"
            )

    except Exception as error:
        logging.exception("AI ERROR")

        error_text = str(error).lower()

        if (
            "429" in error_text
            or "rate limit" in error_text
            or "quota" in error_text
        ):
            answer = "الخدمة مشغولة حالياً 🌷 حاول بعد شوي."
        elif (
            "401" in error_text
            or "api key" in error_text
            or "authentication" in error_text
        ):
            answer = "صار خلل بإعدادات خدمة الذكاء الاصطناعي 🌷"
        else:
            answer = "صار تأخير بسيط بالخدمة 🌷 حاول بعد شوي."

    # لا نكرر تعريف البوت
    if first_contact:
        answer = (
            "آني بوت مكتبة أم القرى، مو صاحب المكتبة 🌷\n"
            + answer
        )

    INTRO_SENT.add(chat_id)

    send_message(
        chat_id,
        answer,
        business_connection_id,
    )

    HISTORY[chat_id].append(("assistant", answer))


