    if asks_pencils(text):

        replies.append(
            pencils_reply()
        )


    # =====================================================
    # الدفاتر
    # =====================================================

    if asks_notebooks(text):

        replies.append(
            "📚 " + notebook_reply(text)
        )


    # =====================================================
    # السجلات
    # =====================================================

    if asks_records(text):

        replies.append(
            records_reply()
        )


    # =====================================================
    # البحث عن المنتجات المحددة
    # =====================================================

    found_products = find_all_products(text)

    for product in found_products:

        # المنتجات التي سبق تعاملنا وياها
        if product in {
            "طباشير",
            "طين اسطناعي",
            "دفتر سجل",
            "سجل شفاف",
            "دفتر سجل كبير",
            "دفتر سجل كبير ملون",
            "صبورة صغيرة",
            "صبورة وسط",
            "صبورة كبيرة",
            "اقلام رصاص ابو الف",
            "باكيت اقلام رصاص الوان",
        }:

            continue

        price = PRICES[product]

        if price == 0:

            replies.append(
                f"📦 {product}: "
                "السعر يحتاج تأكيد من المكتبة 🌷"
            )

        else:

            replies.append(
                f"📦 {product}: {price} دينار."
            )


    # =====================================================
    # حذف التكرار
    # =====================================================

    unique_replies = []

    for reply in replies:

        if reply not in unique_replies:
            unique_replies.append(reply)

    replies = unique_replies


    # =====================================================
    # إذا عدنا جواب مباشر
    # =====================================================

    if replies:

        return "\n\n".join(replies)


    return None


