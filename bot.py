def normalize(text):
    if not text:
        return ""

    text = str(text).lower().strip()

    replacements = {
        "أ": "ا",
        "إ": "ا",
        "آ": "ا",
        "ى": "ي",
        "ة": "ه",
        "ؤ": "و",
        "ئ": "ي",
        "ـ": "",
    }

    for a, b in replacements.items():
        text = text.replace(a, b)

    text = re.sub(r"[\u064B-\u065F\u0670]", "", text)

    # توحيد النجمة والأبعاد
    text = text.replace("×", "*").replace("x", "*")

    # إزالة بعض علامات الترقيم فقط
    text = re.sub(r"[،,؛;!?؟:]+", " ", text)

    text = re.sub(r"\s+", " ", text).strip()

    return text


def tokens(text):
    return [x for x in normalize(text).split() if x]


def similarity(a, b):
    return difflib.SequenceMatcher(
        None,
        normalize(a),
        normalize(b),
    ).ratio()


def token_similarity(a, b):
    aa = set(tokens(a))
    bb = set(tokens(b))

    if not aa or not bb:
        return 0.0

    return len(aa & bb) / max(len(aa), len(bb))


