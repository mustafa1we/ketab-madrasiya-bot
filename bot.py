# البحث عن المنتج
# =========================================================

def find_product(text):

    text = normalize(text)

    products = sorted(
        PRICES.keys(),
        key=lambda x: len(normalize(x)),
        reverse=True
    )

    for product in products:

        product_normalized = normalize(product)

        if product_normalized in text:
            return product

    return None


