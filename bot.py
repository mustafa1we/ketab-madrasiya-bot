def split_requests(text):
    """
    يقسم الرسالة بشكل تقريبي إلى طلبات.
    المطابقة الفعلية تعتمد على المنتجات الموجودة، لذلك حتى
    لو لم تنجح عملية التقسيم نبحث عن كل المنتجات في كامل الرسالة.
    """
    raw_parts = re.split(
        r"\s*(?:و|وهم|ايضا|أيضا|بعد|هم)\s+",
        text,
    )

    parts = [p.strip() for p in raw_parts if p.strip()]

    # إذا التقسيم صار سيئ، نرجع الرسالة كاملة
    if len(parts) > 10:
        return [text]

    return parts


