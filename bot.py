def find_all_products(text):

    text_normalized = normalize(text)

    products = sorted(
        PRICES.keys(),
        key=lambda x: len(normalize(x)),
        reverse=True
    )

    found = []

    for product in products:

        p = normalize(product)

        if p in text_normalized:

            if product not in found:
                found.append(product)

    return found


