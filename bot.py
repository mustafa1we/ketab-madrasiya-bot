# معالجة الرسالة
# =========================================================

def process_message(msg):

    if not msg:
        return

    chat = msg.get("chat")

    if not chat:
        return

    chat_id = chat.get("id")

    if not chat_id:
        return

    business_connection_id = msg.get(
        "business_connection_id"
    )

    # -----------------------------------------------
    # النص
    # -----------------------------------------------

    if "text" in msg:

        text = msg.get(
            "text",
            ""
        ).strip()

        if not text:
            return

        logging.info(
            "Message received | chat=%s | text=%s",
            chat_id,
            text
        )

        # -------------------------------------------
        # Start
        # -------------------------------------------

        if text.startswith("/start"):

            answer = (
                "هلا بيك 🌷\n"
                "آني بوت مكتبة أم القرى، مو صاحب المكتبة، "
                "وأكدر أساعدك بالمنتجات والأسعار المتوفرة عندي."
            )

            save_message(
                chat_id,
                "user",
                text
            )

            save_message(
                chat_id,
                "assistant",
                answer
            )

            send_message(
                chat_id,
                answer,
                business_connection_id
            )

            return

        # -------------------------------------------
        # Help
        # -------------------------------------------

        if text.startswith("/help"):

            answer = (
                "گلي شنو تحتاج 🌷\n"
                "وأساعدك بالمنتجات والأسعار الموجودة عندي."
            )

            send_message(
                chat_id,
                answer,
                business_connection_id
            )

            return

        # -------------------------------------------
        # الرد المباشر
        # -------------------------------------------

        direct = direct_reply(
            text,
            chat_id
        )

        if direct is not None:

            save_message(
                chat_id,
                "user",
                text
            )

            save_message(
                chat_id,
                "assistant",
                direct
            )

            send_message(
                chat_id,
                direct,
                business_connection_id
            )

            return

        # -------------------------------------------
        # AI
        # -------------------------------------------

        try:

            save_message(
                chat_id,
                "user",
                text
            )

            answer = ask_ai(
                text,
                chat_id
            )

            save_message(
                chat_id,
                "assistant",
                answer
            )

            send_message(
                chat_id,
                answer,
                business_connection_id
            )

        except Exception as error:

            logging.exception(
                "AI ERROR"
            )

            # نحذف آخر رسالة user حتى لا تتراكم
            if chat_id in CONVERSATIONS:
                if (
                    CONVERSATIONS[chat_id]
                    and CONVERSATIONS[chat_id][-1]["role"] == "user"
                ):
                    CONVERSATIONS[chat_id].pop()

            error_text = str(error).lower()

            if (
                "429" in error_text
                or "rate limit" in error_text
                or "quota" in error_text
            ):

                error_message = (
                    "الخدمة مشغولة حالياً 🌷 "
                    "حاول بعد شوي."
                )

            elif (
                "401" in error_text
                or "api key" in error_text
                or "authentication" in error_text
            ):

                error_message = (
                    "صار خلل بإعدادات الخدمة 🌷"
                )

            else:

                error_message = (
                    "صار تأخير بسيط بالخدمة 🌷 "
                    "حاول بعد شوي."
                )

            try:

                send_message(
                    chat_id,
                    error_message,
                    business_connection_id
                )

            except Exception:

                logging.exception(
                    "Failed to send error message"
                )

        return

    # -----------------------------------------------
    # صورة / ملف
    # -----------------------------------------------

    if (
        "photo" in msg
        or "document" in msg
    ):

        send_message(
            chat_id,
            "وصلتني الصورة/الملف 🌷 گلي شنو تريد تعرف عنه.",
            business_connection_id
        )

        return

    # -----------------------------------------------
    # رسالة ثانية
    # -----------------------------------------------

    send_message(
        chat_id,
        "آني بوت مكتبة أم القرى وأكدر أساعدك بالمنتجات والأسعار 🌷",
        business_connection_id
    )


