def save_message(chat_id, role, content):
    if chat_id not in CONVERSATIONS:
        CONVERSATIONS[chat_id] = []

    CONVERSATIONS[chat_id].append({
        "role": role,
        "content": content
    })

    # نخلي آخر 12 رسالة فقط
    CONVERSATIONS[chat_id] = CONVERSATIONS[chat_id][-MAX_HISTORY:]


