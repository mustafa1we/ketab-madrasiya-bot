def verify_prices(answer, user_text):

    """
    إذا تعرفنا على منتج بشكل مباشر،
    نضيف تنبيه للـAI بأن السعر يجب أن يكون من القائمة.
    لا نعيد كتابة الجواب بالكامل حتى نحافظ على أسلوب المحادثة.
    """

    products = find_products_direct(user_text)

    if not products:
        return answer

    # فقط منع جملة عامة خاطئة
    generic_phrases = [
        "السعر يحتاج تأكيد من المكتبة 🌷",
        "السعر يحتاج تأكيد من المكتبة"
    ]

    # إذا المنتج معروف عندنا، لا نريد جواب عام فقط
    if len(answer.strip()) < 80:

        lines = []

        for product in products:

            price = PRICES.get(product)

            if price is not None:
                lines.append(
                    f"{product}: {price} دينار"
                )

        if lines:
            return "إي 🌷\n" + "\n".join(lines)

    return answer


