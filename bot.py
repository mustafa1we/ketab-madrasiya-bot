def find_products(text):
    """
    يبحث عن كل المنتجات المذكورة في الرسالة.
    """
    normalized_text = normalize(text)

    found = []

    products = sorted(
        PRICES.keys(),
        key=lambda x: len(normalize(x)),
        reverse=True
    )

    for product in products:
        p = normalize(product)

        if p and p in normalized_text:
            if product not in found:
                found.append(product)

    return found


