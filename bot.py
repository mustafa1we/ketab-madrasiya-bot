def process_message(msg):

    if not msg:
        return

    chat = msg.get("chat")

    if not chat:
        return

    chat_id = chat.get("id")

    if not chat_id:
        return

    # نستخدم chat_id كهوية للمحادثة
    user_id = str(chat_id)

    business_connection_id = msg.get(
        "business_connection_id"
    )

    logging.info(
        "Message received | chat_id=%s | business=%s",
        chat_id,
        bool(business_connection_id)
    )

    # =====================================================
    # نص
    # =====================================================

    if "text" in msg:

        text = msg.get(
            "text",
            ""
        ).strip()

        if not text:
            return

        # -----------------------------------------------
        # /start
        # -----------------------------------------------

        if text.startswith("/start"):

            answer = (
                "هلا بيك 🌷\n"
                "آني بوت مكتبة أم القرى.\n"
                "اكتبلي شنو تحتاج وأساعدك بالمنتجات والأسعار."
            )

            send_message(
                chat_id,
                answer,
                business_connection_id
            )

            introduced_users.add(user_id)

            return

        # -----------------------------------------------
        # /help
        # -----------------------------------------------

        if text.startswith("/help"):

            answer = (
                "اكتب سؤالك بصورة طبيعية 🌷\n"
                "مثلاً: أريد دفاتر وسجلات وشكد سعر الطباشير؟\n"
                "وأرتبلك الجواب."
            )

            send_message(
                chat_id,
                answer,
                business_connection_id
            )

            introduced_users.add(user_id)

            return

        # =================================================
        # حفظ رسالة الزبون قبل التحليل
        # =================================================

        conversation_history[user_id].append({
            "role": "user",
            "content": text
        })

        # =================================================
        # الردود البسيطة
        # =================================================

        simple = simple_reply(text)

        if simple is not None:

            answer = first_message_reply(
                user_id,
                simple
            )

            send_message(
                chat_id,
                answer,
                business_connection_id
            )

            conversation_history[user_id].append({
                "role": "assistant",
                "content": simple
            })

            return

        # =================================================
        # AI
        # =================================================

        try:

            answer = ask_ai(
                user_id,
                text
            )

            # التحقق من الأسعار الواضحة
            answer = verify_prices(
                answer,
                text
            )

            # التعريف في أول تواصل فقط
            answer = first_message_reply(
                user_id,
                answer
            )

            send_message(
                chat_id,
                answer,
                business_connection_id
            )

            # حفظ جواب البوت
            conversation_history[user_id].append({
                "role": "assistant",
                "content": answer
            })

        except Exception as error:

            logging.exception(
                "AI ERROR"
            )

            error_text = str(
                error
            ).lower()

            if (
                "429" in error_text
                or "rate limit" in error_text
                or "quota" in error_text
            ):

                error_message = (
                    "الخدمة مشغولة حالياً 🌷 "
                    "حاول بعد شوي."
                )

            elif (
                "401" in error_text
                or "api key" in error_text
                or "authentication" in error_text
            ):

                error_message = (
                    "صار خلل بإعدادات الخدمة 🌷"
                )

            else:

                error_message = (
                    "صار تأخير بسيط بالخدمة 🌷 "
                    "حاول بعد شوي."
                )

            try:

                send_message(
                    chat_id,
                    error_message,
                    business_connection_id
                )

            except Exception:

                logging.exception(
                    "Failed to send error message"
                )

        return

    # =====================================================
    # صورة أو ملف
    # =====================================================

    if (
        "photo" in msg
        or "document" in msg
    ):

        answer = (
            "وصلتني الصورة/الملف 🌷\n"
            "إذا تريد أسألك عنه أو تعرف سعره، اكتبلي شنو تريد تعرف."
        )

        answer = first_message_reply(
            user_id,
            answer
        )

        send_message(
            chat_id,
            answer,
            business_connection_id
        )

        return

    # =====================================================
    # أنواع رسائل ثانية
    # =====================================================

    send_message(
        chat_id,
        "أكدر أساعدك بالمنتجات والأسعار 🌷",
        business_connection_id
    )


