def ask_ai(user_text, chat_id):

    history = CONVERSATIONS.get(chat_id, [])

    history_text = "\n".join(
        f"{item['role']}: {item['content']}"
        for item in history[-MAX_HISTORY:]
    )

    context = build_price_context(
        user_text,
        history_text
    )

    messages = [
        {
            "role": "system",
            "content": SYSTEM_PROMPT
        }
    ]

    # ذاكرة المحادثة
    for item in history[-MAX_HISTORY:]:
        messages.append({
            "role": item["role"],
            "content": item["content"]
        })

    # معلومات الأسعار المؤكدة
    final_user_message = user_text

    if context:
        final_user_message += (
            "\n\n"
            "معلومات مؤكدة من قائمة مكتبة أم القرى:\n"
            + context
            + "\n\n"
            "استخدم هذه المعلومات فقط إذا كانت مرتبطة بسؤال الزبون."
        )

    messages.append({
        "role": "user",
        "content": final_user_message
    })

    response = client.chat.completions.create(
        model=MODEL,
        messages=messages,
        max_tokens=400
    )

    if not response.choices:
        return "ممكن توضحلي قصدك أكثر؟ 🌷"

    answer = response.choices[0].message.content

    if not answer:
        return "ممكن توضحلي قصدك أكثر؟ 🌷"

    # -----------------------------------------------
    # منع الكلمات
    # -----------------------------------------------

    forbidden = [
        "حبيبي",
        "حبيبتي",
        "عزيزي",
        "عزيزتي"
    ]

    for word in forbidden:
        answer = answer.replace(word, "")

    # -----------------------------------------------
    # منع الردود المزعجة
    # -----------------------------------------------

    answer = answer.replace(
        "وضحلي شنو تحتاج",
        "گلي شنو تقصد 🌷"
    )

    answer = re.sub(
        r"\n{3,}",
        "\n\n",
        answer
    )

    answer = re.sub(
        r"[ \t]{2,}",
        " ",
        answer
    )

    return answer.strip()


