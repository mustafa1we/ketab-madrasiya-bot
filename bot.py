def main():

    logging.info(
        "Bot starting..."
    )

    logging.info(
        "Using model: %s",
        MODEL
    )

    logging.info(
        "Products loaded: %s",
        len(PRICES)
    )

    # حذف Webhook
    remove_webhook()

    offset = None

    while True:

        try:

            params = {
                "timeout": 50,
                "allowed_updates": [
                    "message",
                    "business_message"
                ]
            }

            if offset is not None:
                params["offset"] = offset

            response = requests.get(
                TG + "/getUpdates",
                params=params,
                timeout=65
            )

            # =================================================
            # 409
            # =================================================

            if response.status_code == 409:

                logging.error(
                    "409 Conflict: another bot instance is using this token."
                )

                time.sleep(10)

                continue

            response.raise_for_status()

            data = response.json()

            if not data.get("ok"):

                logging.error(
                    "Telegram API ERROR: %s",
                    data
                )

                time.sleep(5)

                continue

            updates = data.get(
                "result",
                []
            )

            for update in updates:

                update_id = update.get(
                    "update_id"
                )

                if update_id is not None:
                    offset = update_id + 1

                # ---------------------------------------------
                # رسالة عادية
                # ---------------------------------------------

                msg = update.get(
                    "message"
                )

                # ---------------------------------------------
                # Telegram Business
                # ---------------------------------------------

                if msg is None:

                    msg = update.get(
                        "business_message"
                    )

                if not msg:
                    continue

                try:

                    process_message(
                        msg
                    )

                except Exception:

                    logging.exception(
                        "Message processing error"
                    )

        except requests.exceptions.ReadTimeout:

            # طبيعي بسبب Long Polling
            continue

        except requests.exceptions.RequestException:

            logging.exception(
                "Telegram polling error"
            )

            time.sleep(5)

        except Exception:

            logging.exception(
                "Unexpected main loop error"
            )

            time.sleep(5)


