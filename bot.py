def send_message(
    chat_id,
    text,
    business_connection_id=None
):

    if not text:
        text = "ممكن توضحلي قصدك أكثر؟ 🌷"

    data = {
        "chat_id": chat_id,
        "text": str(text)
    }

    if business_connection_id:
        data["business_connection_id"] = business_connection_id

    response = requests.post(
        TG + "/sendMessage",
        json=data,
        timeout=30
    )

    if not response.ok:

        logging.error(
            "TELEGRAM ERROR"
        )

        logging.error(
            "STATUS: %s",
            response.status_code
        )

        logging.error(
            "RESPONSE: %s",
            response.text
        )

        logging.error(
            "CHAT_ID: %s",
            chat_id
        )

        logging.error(
            "BUSINESS_CONNECTION: %s",
            business_connection_id
        )

    response.raise_for_status()


