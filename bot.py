def process_message(msg):

    if not msg:
        return


    chat = msg.get("chat")

    if not chat:
        return


    chat_id = chat.get("id")

    if not chat_id:
        return


    business_connection_id = msg.get(
        "business_connection_id"
    )


    logging.info(
        "Message received | chat_id=%s | business=%s",
        chat_id,
        bool(business_connection_id)
    )


    # =====================================================
    # نص
    # =====================================================

    if "text" in msg:

        text = msg.get(
            "text",
            ""
        ).strip()


        if not text:
            return


        # حفظ رسالة الزبون
        save_user_message(
            chat_id,
            text
        )


        # =================================================
        # START
        # =================================================

        if text.startswith("/start"):

            if chat_id not in WELCOME_SENT:

                WELCOME_SENT.add(chat_id)

                answer = (
                    "هلا بيك 🌷\n"
                    "آني بوت مكتبة أم القرى، مو صاحب المكتبة.\n"
                    "أكدر أساعدك بالمنتجات والأسعار الموجودة عندي."
                )

            else:

                answer = (
                    "هلا بيك 🌷\n"
                    "شنو تحتاج من المكتبة؟"
                )


            send_message(
                chat_id,
                answer,
                business_connection_id
            )

            save_bot_message(
                chat_id,
                answer
            )

            return


        # =================================================
        # HELP
        # =================================================

        if text.startswith("/help"):

            answer = (
                "اكتبلي شنو تحتاج مباشرة 🌷\n"
                "وأساعدك بالمنتجات والأسعار الموجودة عندي."
            )

            send_message(
                chat_id,
                answer,
                business_connection_id
            )

            save_bot_message(
                chat_id,
                answer
            )

            return


        # =================================================
        # الرد المباشر الذكي
        # =================================================

        try:

            direct = direct_reply(
                chat_id,
                text
            )

        except Exception:

            logging.exception(
                "Direct reply error"
            )

            direct = None


        if direct is not None:

            send_message(
                chat_id,
                direct,
                business_connection_id
            )

            save_bot_message(
                chat_id,
                direct
            )

            return


        # =================================================
        # الذكاء الاصطناعي
        # =================================================

        try:

            answer = ask_ai(
                chat_id,
                text
            )


            send_message(
                chat_id,
                answer,
                business_connection_id
            )


            save_bot_message(
                chat_id,
                answer
            )


        except Exception as error:

            logging.exception(
                "AI ERROR"
            )


            error_text = str(
                error
            ).lower()


            if (
                "429" in error_text
                or "rate limit" in error_text
                or "quota" in error_text
            ):

                error_message = (
                    "الخدمة مشغولة حالياً 🌷 "
                    "حاول بعد شوي."
                )


            elif (
                "401" in error_text
                or "api key" in error_text
                or "authentication" in error_text
            ):

                error_message = (
                    "صار خلل بإعدادات الخدمة 🌷"
                )


            else:

                error_message = (
                    "صار تأخير بسيط بالخدمة 🌷 "
                    "حاول بعد شوي."
                )


            try:

                send_message(
                    chat_id,
                    error_message,
                    business_connection_id
                )

                save_bot_message(
                    chat_id,
                    error_message
                )

            except Exception:

                logging.exception(
                    "Failed to send error message"
                )


        return


    # =====================================================
    # صورة أو ملف
    # =====================================================

    if (
        "photo" in msg
        or "document" in msg
    ):

        answer = (
            "وصلتني الصورة/الملف 🌷\n"
            "گلي شنو تريد تعرف عنه."
        )

        send_message(
            chat_id,
            answer,
            business_connection_id
        )

        save_bot_message(
            chat_id,
            answer
        )

        return


    # =====================================================
    # أنواع رسائل ثانية
    # =====================================================

    answer = (
        "أكدر أساعدك بكل ما يخص مكتبة أم القرى 🌷"
    )

    send_message(
        chat_id,
        answer,
        business_connection_id
    )

    save_bot_message(
        chat_id,
        answer
    )


