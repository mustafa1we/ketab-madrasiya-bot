def exact_product_matches(text):
    ntext = normalize(text)
    found = []

    # الأطول أولاً حتى لا يلتقط "سجل" قبل "سجل 200 سيم شفاف"
    candidates = sorted(
        ALIAS_INDEX.items(),
        key=lambda x: len(x[0]),
        reverse=True,
    )

    for alias, products in candidates:
        if not alias:
            continue

        # تطابق كلمة/عبارة داخل الرسالة
        if alias in ntext:
            for product in products:
                if product not in found:
                    found.append(product)

    return found


def fuzzy_product_candidates(text, limit=6):
    ntext = normalize(text)

    if not ntext:
        return []

    candidates = []

    # لا نعمل fuzzy على كلمات قصيرة جداً
    for alias, products in ALIAS_INDEX.items():
        if len(alias) < 3:
            continue

        score_full = similarity(ntext, alias)
        score_token = token_similarity(ntext, alias)

        # نبحث أيضاً بكل كلمة/مقطع من الرسالة
        best_piece = 0.0
        for piece in ntext.split():
            if len(piece) >= 3:
                best_piece = max(best_piece, similarity(piece, alias))

        score = max(
            score_full,
            score_token,
            best_piece * 0.92,
        )

        if score >= FUZZY_THRESHOLD:
            for product in products:
                candidates.append((score, product))

    candidates.sort(reverse=True)

    output = []
    seen = set()

    for score, product in candidates:
        if product not in seen:
            seen.add(product)
            output.append((score, product))

        if len(output) >= limit:
            break

    return output


def find_products(text):
    exact = exact_product_matches(text)

    if exact:
        return exact

    fuzzy = fuzzy_product_candidates(text)

    if fuzzy:
        # نأخذ فقط النتائج القوية
        top_score = fuzzy[0][0]

        if top_score >= 0.78:
            return [p for s, p in fuzzy if s >= max(0.68, top_score - 0.10)]

    return []


